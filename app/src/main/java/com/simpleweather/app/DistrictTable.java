    /** v9.47：多段切分匹配——依次尝试 省+市+区 / 省+市 / 省+区 / 市+区，
     *  切分位置不固定：前缀能识别为省级则按省处理，否则按市+区组合，
     *  根除「浙江温州」这类带省前缀输入匹配不到的问题。 */
    private static boolean matchSegments(String t, String cityN, String areaN) {
        int n = t.length();
        // 省段：只试前 4 个字符（最长省名 3 字 + 容忍 1 字后缀）
        int maxP = Math.min(n - 1, 4);
        for (int c1 = 1; c1 <= maxP; c1++) {
            String s1 = t.substring(0, c1);
            if (!isProvince(s1)) continue;
            String rest = t.substring(c1);
            int rn = rest.length();
            // 省 + 市 + 区：如「浙江温州鹿城」
            for (int c2 = 1; c2 < rn; c2++) {
                if (cityN.contains(norm(rest.substring(0, c2)))
                        && areaN.contains(norm(rest.substring(c2)))) {
                    return true;
                }
            }
            // 省 + 市：如「浙江温州」「浙江省温州市」
            if (cityN.contains(norm(rest))) return true;
            // 省 + 区：如「浙江西湖」（重名区由调用方多候选选择）
            if (areaN.contains(norm(rest))) return true;
        }
        // 市 + 区：如「深圳宝安」（无省前缀时按原双段逻辑）
        for (int cut = 1; cut < n; cut++) {
            if (cityN.contains(norm(t.substring(0, cut)))
                    && areaN.contains(norm(t.substring(cut)))) {
                return true;
            }
        }
        return false;
    }

    /** 区县名去后缀："宝安区"->"宝安"；"青龙满族自治县"->"青龙" */
    private static String norm(String s) {
        String t = s.trim();
        for (String suf : new String[]{"自治县", "自治旗", "林区", "矿区",
                "新区", "特区", "区", "县", "市", "旗"}) {
            if (t.endsWith(suf)) {
                t = t.substring(0, t.length() - suf.length());
                break;
            }
        }
        return t;
    }
