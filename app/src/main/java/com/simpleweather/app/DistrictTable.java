    private static String formatName(String area, String city) {
        String prov = CityTable.provinceOf(city);
        if (prov == null || prov.isEmpty()) return area + " · " + city;   // 查不到省兜底旧格式
        if ("省直辖县级行政区划".equals(city)) return prov + " · " + area;
        if (prov.equals(CityTable.cityFull(city))) return prov + " · " + area;
        return prov + " · " + CityTable.cityFull(city) + " · " + area;
    }

